"""뻘글·잡담 계정용 토픽 뱅크 — 아이디어가 없을 때 뽑아쓰기."""
from __future__ import annotations

import random

# 카테고리별 잡담 소재 — 직접 글 쓸 때 시드용
TOPICS = [
    # 일상 관찰형
    "오늘 본 것 중 제일 이상했던 거",
    "요즘 자주 쓰는 앱 하나랑 그 이유",
    "점심 메뉴 고르는 알고리즘",
    "카페에서 옆 테이블 대화 엿들은 것",
    # 개발자/도구 일상
    "오늘 삽질한 거 (에러 하나 소개)",
    "만든 도구가 처음 제대로 돌았을 때 기분",
    "밤에 코드 짜다 멍 때린 얘기",
    "자동화했다가 더 귀찮아진 것",
    # AI 잡담
    "AI한테 시켰는데 이상하게 나온 것",
    "딥페이크 영상 보고 구분 못한 경험",
    "요즘 AI 뉴스 중 제일 과장된 것",
    "AI가 못 할 것 같은데 해버린 것",
    # 참여 유도형
    "여러분은 [주제] 어떻게 하세요?",
    "이거 저만 그런가요: [사소한 습관]",
    "A vs B 하나만 골라야 한다면",
    # 자기소개/뒷얘기형
    "이 계정 만든 이유",
    "요즘 파고 있는 것",
    "이번 주에 배운 것 하나",
    "하고 싶은데 못 하고 있는 것",
]

HOT_TAKE_STARTERS = [
    "솔직히", "근데 진짜", "아니 근데", "인정할 건 인정해야 함.",
    "오늘 깨달은 건데", "이 말 하면 욕먹을 수도 있는데",
]


def idea(n: int = 3) -> list[str]:
    picks = random.sample(TOPICS, min(n, len(TOPICS)))
    starter = random.choice(HOT_TAKE_STARTERS)
    return [f"• {p}" for p in picks] + [f"• 오프너 예시: “{starter} …”"]
